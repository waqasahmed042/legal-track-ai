// Function to find the category for a given heading
export function findCategoryForHeading(heading: string): string {
    if (!heading) return "";

    // Convert heading to lowercase for case-insensitive matching
    const headingLower = heading.toLowerCase();

    // Check each category and its alternate names
    for (const [category, alternateNames] of Object.entries(categoryMappings)) {
        // Check if the heading matches the category name
        if (headingLower.includes(category.toLowerCase())) {
            return category;
        }

        // Check if the heading matches any of the alternate names
        for (const altName of alternateNames) {
            // Split the alternate name into words and check if any word is in the heading
            const altWords = altName.toLowerCase().split(/\s+/);
            for (const word of altWords) {
                if (word.length > 2 && headingLower.includes(word)) {
                    return category;
                }
            }
        }
    }

    return "";
}